## NICHESv2_inputs --------------------------------------------------------

#' Example NICHESv2 inputs (raw triple)
#'
#' A small synthetic dataset providing the three raw inputs required to
#' construct a \code{NICHESObject}: a sparse expression matrix, a per-cell
#' metadata table with spatial coordinates and cell-type labels, and a
#' ligand--receptor database. Used by the example blocks of upstream
#' constructors such as \code{\link{create_NICHESObject}},
#' \code{\link{compute_CellToCell}}, and the
#' \code{create_Edgelist_*} family.
#'
#' The three components share barcodes and gene names so the standard
#' upstream pipeline runs end-to-end without any additional data wrangling.
#'
#' @format A named list with three components:
#' \describe{
#'   \item{\code{count.mtx}}{50 x 80 \code{dgCMatrix} of UMI counts
#'     (genes x cells). Approximately 25\% non-zero density.}
#'   \item{\code{meta.data}}{80-row \code{data.frame} with columns
#'     \code{x}, \code{y} (spatial coordinates), \code{nCount_RNA}
#'     (per-cell library size), and \code{celltype} (one of
#'     \code{"TypeA"}, \code{"TypeB"}, \code{"TypeC"} forming three
#'     spatial clusters). Row names are cell barcodes.}
#'   \item{\code{LRM.db}}{15-row \code{data.frame} with columns
#'     \code{ligand}, \code{receptor}, \code{pathway}. Three rows use
#'     underscore-delimited gene complexes (\code{"GeneA_GeneB"}) so
#'     example output exercises the complex-handling code path.}
#' }
#'
#' @source Synthetic data generated by
#'   \code{data-raw/build_NICHESv2_example.R}. Deterministic
#'   (\code{set.seed(42)}).
#'
#' @seealso \code{\link{NICHESv2_example}} for the prebuilt
#'   \code{NICHESObject} constructed from these inputs.
#'
#' @examples
#' data(NICHESv2_inputs)
#' str(NICHESv2_inputs, max.level = 1)
#' dim(NICHESv2_inputs$count.mtx)
#' table(NICHESv2_inputs$meta.data$celltype)
#' head(NICHESv2_inputs$LRM.db)
"NICHESv2_inputs"


## NICHESv2_example ------------------------------------------------------

#' Example prebuilt NICHESObject
#'
#' A small \code{NICHESObject} produced by running the standard upstream
#' pipeline on \code{\link{NICHESv2_inputs}}: a spatial edge list with
#' \code{k = 5}, ligand--receptor scoring with \code{method = "product"},
#' and proportional normalisation. Used by the example blocks of downstream
#' functions including \code{\link{add_neighborhoods}},
#' \code{\link{Aggregate_CellToCell_Edges}},
#' \code{\link{CellToCell_InSitu}}, \code{\link{add_cell_meta}}, and the
#' S3 methods of \code{NICHESObject}.
#'
#' Two slot families are intentionally left \code{NULL}:
#' \itemize{
#'   \item \strong{Neighborhood slots}
#'         (\code{$neighborhood.cell.list},
#'         \code{$neighborhood.edge.list}, \code{$neighborhood.meta}) --
#'         so that \code{\link{add_neighborhoods}} examples demonstrate
#'         the actual transformation.
#'   \item \strong{\code{$segmentation}} -- so that
#'         \code{\link{add_segmentation}} examples have an unsegmented
#'         starting point.
#' }
#' All other 11 slots are populated.
#'
#' @format A \code{NICHESObject} containing 80 cells, 50 genes, 15 LRM
#'   pairs, and approximately 400 spatial edges.
#'
#' @source Synthetic data generated by
#'   \code{data-raw/build_NICHESv2_example.R}. Deterministic
#'   (\code{set.seed(42)}).
#'
#' @seealso \code{\link{NICHESv2_inputs}} for the raw triple of inputs;
#'   \code{\link{create_NICHESObject}} for the constructor that produces
#'   this object.
#'
#' @examples
#' data(NICHESv2_example)
#' print(NICHESv2_example)
#' dim(NICHESv2_example)
#' length(NICHESv2_example)
"NICHESv2_example"
